const icon = (r) => RESOURCE_INFO[r]?.icon || '';
const name = (r) => RESOURCE_INFO[r]?.name || r;
const pct = (x) => `${Math.round(x * 100)}%`;
const costText = (cost) => Object.entries(cost || {}).map(([r, n]) => `${icon(r)}${n}`).join(' ') || '—';
const flow = (o) => Object.entries(o || {}).map(([r, n]) => `${icon(r)} ${name(r)} ${n}`).join(', ');

function jobText(t, d) {
  if (d.job === 'gather') {
    const node = { tree: 'ต้นไม้', rock: 'ก้อนหิน', berry: 'พุ่มเบอร์รี่', ore: 'เส้นแร่บนที่สูง' }[d.node];
    return `เก็บจาก${node} (รัศมี ${GATHER_RADIUS} ม.${d.keepNode ? ' ไม่ทำให้ต้นไม้หมด' : ''}) → ${flow(d.output)}`;
  }
  if (d.job === 'fish') return `ตกปลาริมน้ำ (ต้องวางติดแหล่งน้ำ, รัศมี ${FISH_RADIUS} ม.) → ${flow(d.output)}`;
  if (d.job === 'hunt') return `ล่ากวางป่า (รัศมี ${HUNT_RADIUS} ม.) → ${flow(d.output)}`;
  if (d.job === 'ranch') return `เลี้ยงแกะในคอก สลับผลิต ${(d.outputs || []).map(flow).join(' / ')}`;
  if (d.job === 'doctor' || d.job === 'market') {
    return `${NEED_INFO[d.service]} ให้บ้านในรัศมี ${d.serviceRadius} ม. · ต้องมี ${icon(d.supply)} ${name(d.supply)} ในคลังของอาคาร (สูงสุด ${SUPPLY_MAX})`;
  }
  if (d.job === 'farm') return `ทำนาในโซนไร่นา (รัศมี ${FIELD_RADIUS} ม.) → ${flow(d.output)}*`;
  if (d.job === 'process') return `${flow(d.input)} → ${flow(d.output)}`;
  if (d.job === 'service') return `${NEED_INFO[d.service]} ให้บ้านในรัศมี ${d.serviceRadius} ม.`;
  if (d.storage) return 'เก็บสินค้าทุกชนิด';
  return '';
}

function buildingRows(category) {
  return Object.entries(BUILDINGS)
    .filter(([, d]) => d.category === category && !d.monument)
    .map(([t, d]) => `<tr><td><b>${d.name}</b></td><td>${costText(d.cost)}</td><td>${d.workers || '—'}</td>
      <td>${jobText(t, d)}</td><td>${d.unlockPop ? `👥 ${d.unlockPop}` : 'ทันที'}</td></tr>`)
    .join('');
}

